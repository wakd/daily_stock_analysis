export type ScreeningTranslator = (source: string, ...values: unknown[]) => string;

function makeTranslator(language: UiLanguage): ScreeningTranslator {
  return (source, ...values) => {
    const template = language === 'en' && Object.hasOwn(english, source) ? english[source] : source;
    return values.length ? template.replace(/\{(\d+)\}/g, (_, index: string) => String(values[Number(index)])) : template;
  };
}

export const SCREENING_TEXT = { en: makeTranslator('en'), zh: makeTranslator('zh') };

export function screeningServiceMessage(translate: ScreeningTranslator, message: string): string {
  const count = message.match(/^(?:快照筛选完成，保留 |选股已完成，正在整理 )(\d+) 条候选$/);
  return count ? translate(message.replace(count[1], '{0}'), count[1]) : translate(message);
}
